// include/pingcore/route_compiler.h
// PingCore Route Compiler, Symbol Isolation & Manifest Generator (PKG-120)
#pragma once

#include <pingcore/router.h>
#include <pingdart/web/url_security.h>
#include <string>
#include <string_view>
#include <vector>
#include <unordered_set>
#include <filesystem>
#include <fstream>
#include <sstream>
#include <iostream>

namespace pingcore {

class RouteCompiler {
public:
    struct CompilationResult {
        bool success{false};
        std::string error_message;
        size_t page_count{0};
        size_t api_route_count{0};
        std::filesystem::path client_manifest_path;
        std::filesystem::path server_manifest_path;
    };

    static CompilationResult compile(const std::filesystem::path& project_dir) {
        CompilationResult res;
        std::filesystem::path app_dir = project_dir / "app";

        if (!std::filesystem::exists(app_dir)) {
            res.error_message = "Project does not contain an app/ directory: " + app_dir.string();
            return res;
        }

        auto scan = RouteScanner::scan(app_dir);

        // 1. Security & Ambiguity Validation
        std::unordered_set<std::string> seen_routes;
        for (const auto& page : scan.pages) {
            // URL Security check
            if (!pingdart::web::UrlSecurity::is_safe_uri_path(page.route_path)) {
                res.error_message = "Security Violation: Unsafe route path detected: " + page.route_path;
                return res;
            }

            // Ambiguity check
            if (seen_routes.find(page.route_path) != seen_routes.end()) {
                res.error_message = "Route Collision: Duplicate route registration detected: " + page.route_path;
                return res;
            }
            seen_routes.insert(page.route_path);
        }

        // 2. Create generated output directory: .pingcore/generated
        std::error_code ec;
        std::filesystem::path gen_dir = project_dir / ".pingcore" / "generated";
        std::filesystem::create_directories(gen_dir, ec);
        if (ec) {
            res.error_message = "Failed to create generated directory: " + gen_dir.string();
            return res;
        }

        // 3. Generate routes_client.g.cpp
        std::filesystem::path client_cpp = gen_dir / "routes_client.g.cpp";
        std::ofstream cf(client_cpp);
        if (!cf.is_open()) {
            res.error_message = "Failed to open client manifest file: " + client_cpp.string();
            return res;
        }

        cf << "// .pingcore/generated/routes_client.g.cpp\n"
           << "// Auto-generated by PingCore Route Compiler (Zero Symbol Collision)\n"
           << "#include <pingcore/app.h>\n"
           << "#include <pingcore/ui.h>\n"
           << "#include <pingcore/router.h>\n\n"
           << "using namespace pingcore;\n\n";

        // Wrap layout if exists
        bool has_root_layout = !scan.layouts.empty();
        if (has_root_layout) {
            cf << "namespace pingcore_routes::_layout {\n"
               << "#include \"" << std::filesystem::relative(scan.layouts[0].file_path, gen_dir).string() << "\"\n"
               << "}\n\n";
        }

        // Wrap not_found if exists
        if (!scan.not_found_file.empty()) {
            cf << "namespace pingcore_routes::_not_found {\n"
               << "#include \"" << std::filesystem::relative(scan.not_found_file, gen_dir).string() << "\"\n"
               << "}\n\n";
        }

        // Wrap each page in its isolated namespace
        std::vector<std::pair<std::string, std::string>> page_registrations; // {route_path, namespace}
        for (size_t i = 0; i < scan.pages.size(); ++i) {
            const auto& page = scan.pages[i];
            std::string ns_name = "page_" + std::to_string(i);
            cf << "namespace pingcore_routes::" << ns_name << " {\n"
               << "#include \"" << std::filesystem::relative(page.file_path, gen_dir).string() << "\"\n"
               << "}\n\n";
            page_registrations.push_back({page.route_path, "pingcore_routes::" + ns_name});
        }

        // Generate registration and main() entry point
        cf << "void register_all_routes() {\n";
        if (has_root_layout) {
            cf << "    router().register_layout(\"/\", pingcore_routes::_layout::Layout);\n";
        }
        if (!scan.not_found_file.empty()) {
            cf << "    router().register_not_found(pingcore_routes::_not_found::NotFound);\n";
        }
        for (const auto& [route, ns] : page_registrations) {
            cf << "    router().register_page(\"" << route << "\", " << ns << "::Page);\n";
        }
        cf << "}\n\n";

        cf << "int main(int argc, char* argv[]) {\n"
           << "    (void)argc; (void)argv;\n"
           << "    App app(\"" << project_dir.filename().string() << "\");\n"
           << "    register_all_routes();\n"
           << "    return app.useRouter().run();\n"
           << "}\n";
        cf.close();

        // 4. Generate routes_server.g.cpp
        std::filesystem::path server_cpp = gen_dir / "routes_server.g.cpp";
        std::ofstream sf(server_cpp);
        if (!sf.is_open()) {
            res.error_message = "Failed to open server manifest file: " + server_cpp.string();
            return res;
        }

        sf << "// .pingcore/generated/routes_server.g.cpp\n"
           << "// Auto-generated by PingCore Route Compiler\n"
           << "#include <pingcore/server.h>\n"
           << "#include <iostream>\n\n"
           << "using namespace pingcore;\n\n";

        std::vector<std::pair<std::string, std::string>> api_registrations;
        for (size_t i = 0; i < scan.api_routes.size(); ++i) {
            const auto& api = scan.api_routes[i];
            std::string ns_name = "api_" + std::to_string(i);
            sf << "namespace pingcore_api::" << ns_name << " {\n"
               << "#include \"" << std::filesystem::relative(api.file_path, gen_dir).string() << "\"\n"
               << "}\n\n";
            api_registrations.push_back({api.api_path, "pingcore_api::" + ns_name});
        }

        sf << "int main() {\n"
           << "    Server server;\n";
        for (const auto& [path, ns] : api_registrations) {
            sf << "    server.get(\"" << path << "\", [](const Request& req, Response& res) {\n"
               << "        Request non_const_req = req;\n"
               << "        res = " << ns << "::GET(non_const_req);\n"
               << "    });\n";
        }
        sf << "    std::cout << \"[PingCore Server] Listening on http://localhost:8080...\" << std::endl;\n"
           << "    return server.listen(8080).ok() ? 0 : 1;\n"
           << "}\n";
        sf.close();

        // 5. Generate production routes_manifest.json
        {
            std::ofstream mf(gen_dir / "routes_manifest.json");
            mf << "{\n"
               << "  \"framework\": \"PingCore\",\n"
               << "  \"version\": \"1.0.0\",\n"
               << "  \"pages\": [\n";
            for (size_t i = 0; i < scan.pages.size(); ++i) {
                mf << "    {\"route\": \"" << scan.pages[i].route_path << "\", \"file\": \"" << scan.pages[i].file_path << "\"}";
                if (i + 1 < scan.pages.size()) mf << ",";
                mf << "\n";
            }
            mf << "  ],\n"
               << "  \"api_routes\": [\n";
            for (size_t i = 0; i < scan.api_routes.size(); ++i) {
                mf << "    {\"path\": \"" << scan.api_routes[i].api_path << "\", \"file\": \"" << scan.api_routes[i].file_path << "\"}";
                if (i + 1 < scan.api_routes.size()) mf << ",";
                mf << "\n";
            }
            mf << "  ]\n"
               << "}\n";
        }

        res.success = true;
        res.page_count = scan.pages.size();
        res.api_route_count = scan.api_routes.size();
        res.client_manifest_path = client_cpp;
        res.server_manifest_path = server_cpp;
        return res;
    }
};

} // namespace pingcore
